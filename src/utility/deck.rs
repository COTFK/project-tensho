pub const fn unpack_setcode(packed: u64) -> [u16; 4] {
    [
        (packed & 0xFFFF) as u16,          // Block 1 (Lowest)
        ((packed >> 16) & 0xFFFF) as u16,   // Block 2
        ((packed >> 32) & 0xFFFF) as u16,   // Block 3
        ((packed >> 48) & 0xFFFF) as u16,   // Block 4 (Highest)
    ]
}

